// Writes contracts/pool/src/poseidon_params.rs: circomlib's Poseidon constants
// (round constants C and MDS matrix M) for t = 2, 3, 4, taken from poseidon-lite
// (app/node_modules), as 32-byte big-endian field elements. The contract feeds
// them to the Soroban host's poseidon_permutation, so the pool hashes notes and
// tree nodes exactly as circuits/spend.circom does.
//   node circuits/gen-poseidon-params.mjs
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '../app/package.json'))
// Absolute paths: the package's export map hides its constants files.
const lite = (file) => require(join(here, '../app/node_modules/poseidon-lite', file))
const { version } = lite('package.json')
// The constants are base64 big-endian numbers.
const decode = (o) => (Array.isArray(o) ? o.map(decode) : BigInt('0x' + Buffer.from(o, 'base64').toString('hex')))

const ROUNDS_F = 8
const ROUNDS_P = { 2: 56, 3: 57, 4: 56 }

const hex = (n) => n.toString(16).padStart(64, '0')
const arr = (n) => `[${hex(n).match(/../g).map((b) => `0x${b}`).join(', ')}]`

let out = `// Generated by circuits/gen-poseidon-params.mjs from poseidon-lite ${version}
// (circomlib's Poseidon constants over the BN254 scalar field). Do not edit.
//
// For each state width t: the (ROUNDS_F + rounds_p) x t round constants and
// the t x t MDS matrix, as 32-byte big-endian field elements.

pub const ROUNDS_F: u32 = ${ROUNDS_F};

pub struct Params {
    pub t: u32,
    pub rounds_p: u32,
    /// (ROUNDS_F + rounds_p) * t constants, round-major.
    pub c: &'static [[u8; 32]],
    /// t * t matrix, row-major.
    pub m: &'static [[u8; 32]],
}
`
for (const t of [2, 3, 4]) {
  const mod = lite(`constants/${t - 1}.js`)
  const raw = mod.default ?? mod
  const C = decode(raw.C)
  const M = decode(raw.M)
  const rounds = ROUNDS_F + ROUNDS_P[t]
  if (C.length !== rounds * t) throw new Error(`t=${t}: ${C.length} constants, expected ${rounds * t}`)
  if (M.length !== t || M.some((r) => r.length !== t)) throw new Error(`t=${t}: bad M`)
  out += `
pub const T${t}: Params = Params {
    t: ${t},
    rounds_p: ${ROUNDS_P[t]},
    c: &[
${C.map((n) => `        ${arr(n)},`).join('\n')}
    ],
    m: &[
${M.flat().map((n) => `        ${arr(n)},`).join('\n')}
    ],
};
`
}
const target = join(here, '../contracts/pool/src/poseidon_params.rs')
writeFileSync(target, out)
console.log(`wrote ${target} (${out.length} bytes)`)
